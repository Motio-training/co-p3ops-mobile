// Un .xlsx est un fichier ZIP contenant du XML ; les fichiers sont rangés sans compression.

const enc = new TextEncoder();
const XML_BAD = /[\x00-\x08\x0b\x0c\x0e-\x1f]/g;

function xml(text) {
  return String(text).replace(XML_BAD, '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function col(i) {
  let s = '';
  let n = i + 1;
  while (n) {
    const r = (n - 1) % 26;
    s = String.fromCharCode(65 + r) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

function sheetNames(names) {
  const out = [];
  const seen = new Set();
  for (const name of names) {
    const base = String(name || 'Feuille').replace(/[[\]:*?/\\]/g, '-').replace(/^[' ]+|[' ]+$/g, '').slice(0, 31) || 'Feuille';
    let cand = base;
    for (let k = 2; seen.has(cand.toLowerCase()); k++) {
      const suffix = ` (${k})`;
      cand = base.slice(0, 31 - suffix.length) + suffix;
    }
    seen.add(cand.toLowerCase());
    out.push(cand);
  }
  return out;
}

